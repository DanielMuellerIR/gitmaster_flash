#!/usr/bin/env python3
"""Linux-Wrapper im Benutzerkonto einrichten; keine Pakete oder Systemdateien ändern."""
from __future__ import annotations

import argparse
import datetime
import os
from pathlib import Path
import re
import shlex
import shutil
import stat
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import gitmaster_flash as g

MARKER = '# Generated by gitmaster_flash install-linux.sh'
START = '# >>> gitmaster_flash >>>'
END = '# <<< gitmaster_flash <<<'
UNSET = object()


class DependencyError(ValueError):
    pass


def quote_fish(value: str) -> str:
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def wrapper_text(repo: Path, shell: str) -> str:
    script = str(repo / 'gitmaster_flash.py')
    if shell == 'fish':
        return MARKER + '\n' + '''function gmf
    set -l gmf_tmp /tmp
    if set -q TMPDIR; and test -n "$TMPDIR"
        set gmf_tmp "$TMPDIR"
    end
    set -l gmf_cdfile (mktemp "$gmf_tmp/gmf-cd.XXXXXXXX"); or return 1
    command python3 SCRIPT --cd-file "$gmf_cdfile" $argv
    set -l gmf_result $status
    set -l gmf_target ''
    if test -s "$gmf_cdfile"
        read --null --delimiter '' gmf_target < "$gmf_cdfile"
    end
    command rm -f -- "$gmf_cdfile"
    if test -n "$gmf_target"; and test -d "$gmf_target"
        cd -- "$gmf_target"; or return 1
    end
    return $gmf_result
end
'''.replace('SCRIPT', quote_fish(script))
    return MARKER + '\n' + '''gmf() {
    local gmf_cdfile gmf_target='' gmf_result=0
    gmf_cdfile=$(mktemp "${TMPDIR:-/tmp}/gmf-cd.XXXXXXXX") || return 1
    command python3 SCRIPT --cd-file "$gmf_cdfile" "$@" || gmf_result=$?
    if [ -s "$gmf_cdfile" ]; then
        IFS= read -r -d '' gmf_target < "$gmf_cdfile" || :
    fi
    command rm -f -- "$gmf_cdfile"
    if [ -n "$gmf_target" ] && [ -d "$gmf_target" ]; then
        cd -- "$gmf_target" || return 1
    fi
    return "$gmf_result"
}
'''.replace('SCRIPT', shlex.quote(script))


def checked_syntax(shell: str, content: bytes) -> None:
    options = {'bash': ['--noprofile', '--norc', '-n'],
               'zsh': ['-f', '-n'], 'fish': ['--no-config', '-n']}
    environment = dict(os.environ)
    for key in ('BASH_ENV', 'ENV'):
        environment.pop(key, None)
    result = subprocess.run([shell, *options[shell]], input=content, capture_output=True,
                            timeout=10, env=environment)
    if result.returncode or result.stderr:
        raise ValueError(g.t('linux_syntax', shell=shell))


def atomic_write(path: Path, data: bytes, *, backup: bool = False, expected=UNSET) -> None:
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise ValueError(g.t('linux_file_conflict', p=g.display_git_path(path)))
    original = path.read_bytes() if path.exists() else None
    if expected is not UNSET and original != expected:
        raise ValueError(g.t('linux_file_conflict', p=g.display_git_path(path)))
    if original == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(path.stat().st_mode) if original is not None else 0o600
    if backup and original is not None:
        timestamp = datetime.datetime.now(datetime.timezone.utc).isoformat(
            timespec='microseconds').replace('+00:00', 'Z')
        saved = path.with_name(path.name + '.gmf-backup-' + timestamp)
        saved_fd = os.open(saved, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
        with os.fdopen(saved_fd, 'wb') as stream:
            stream.write(original)
        saved.chmod(mode)
    fd, temporary = tempfile.mkstemp(prefix='.gmf-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            os.fchmod(stream.fileno(), mode)
        # Ein während der Vorbereitung geänderter Inhalt darf nicht verloren gehen.
        if path.is_symlink() or (path.read_bytes() if path.exists() else None) != original:
            raise ValueError(g.t('linux_file_conflict', p=g.display_git_path(path)))
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def registration(original: bytes, wrapper: Path) -> bytes:
    start, end = START.encode(), END.encode()
    block = (START + '\nsource -- ' + shlex.quote(str(wrapper)) + '\n' + END + '\n').encode()
    lines = original.splitlines(keepends=True)
    starts = [i for i, line in enumerate(lines) if line.rstrip(b'\r\n') == start]
    ends = [i for i, line in enumerate(lines) if line.rstrip(b'\r\n') == end]
    if starts or ends:
        if len(starts) != 1 or len(ends) != 1 or starts[0] >= ends[0]:
            raise ValueError(g.t('linux_registration_conflict'))
        return b''.join(lines[:starts[0]]) + block + b''.join(lines[ends[0] + 1:])
    # Andere gmf-Definitionen nicht still überschreiben; Shell-Code wird nie ausgeführt.
    if re.search(rb'(?m)^\s*(?:function\s+gmf\b|gmf\s*\(\s*\)|alias\s+gmf=|[^#\n]*(?:source|\.)\s+[^\n]*gmf\.(?:zsh|bash))', original):
        raise ValueError(g.t('linux_registration_conflict'))
    return original + b'\n\n' + block


def install(repo: Path, home: Path, shell: str, config: Path, zdotdir: Path) -> Path:
    if shell not in ('bash', 'fish', 'zsh'):
        raise ValueError(g.t('linux_shell'))
    if not all(p.is_absolute() for p in (repo, home, config, zdotdir)):
        raise ValueError(g.t('linux_absolute'))
    wrapper = (config / 'fish/functions/gmf.fish' if shell == 'fish'
               else config / f'gitmaster_flash/shell/gmf.{shell}')
    content = wrapper_text(repo, shell).encode('utf-8')
    if wrapper.exists() or wrapper.is_symlink():
        if wrapper.is_symlink() or not wrapper.is_file() or not wrapper.read_bytes().startswith((MARKER + '\n').encode()):
            raise ValueError(g.t('linux_file_conflict', p=g.display_git_path(wrapper)))
    checked_syntax(shell, content)
    rc = None
    updated = None
    if shell != 'fish':
        rc = home / '.bashrc' if shell == 'bash' else zdotdir / '.zshrc'
        if rc.is_symlink() or (rc.exists() and not rc.is_file()):
            raise ValueError(g.t('linux_file_conflict', p=g.display_git_path(rc)))
        original = rc.read_bytes() if rc.exists() else None
        active_lines = b'\n'.join(line for line in (original or b'').splitlines()
                                  if not line.lstrip().startswith(b'#'))
        if b'<<' in active_lines:
            raise ValueError(g.t('linux_complex_rc'))
        checked_syntax(shell, original or b'')
        updated = registration(original or b'', wrapper)
        checked_syntax(shell, updated)
    atomic_write(wrapper, content)
    if rc is not None:
        atomic_write(rc, updated, backup=True, expected=original)
    return wrapper


def prerequisites(shell: str) -> None:
    if sys.version_info < (3, 9) or not shutil.which('git') or not shutil.which(shell):
        raise DependencyError(g.t('linux_dependencies', shell=shell))
    import curses  # noqa: F401 — fehlendes curses muss vor Schreibarbeit auffallen.
    version = subprocess.run(['git', '--version'], capture_output=True, text=True, timeout=10)
    match = re.search(r'(\d+)\.(\d+)', version.stdout)
    if version.returncode or match is None or tuple(map(int, match.groups())) < (2, 36):
        raise DependencyError(g.t('linux_dependencies', shell=shell))


def main(argv=None) -> int:
    language = argparse.ArgumentParser(add_help=False)
    language.add_argument('--lang', choices=('en', 'de'))
    known, _ = language.parse_known_args(argv)
    g.set_ui_lang(g.resolve_lang(g.DEFAULT_CONFIG, known.lang))
    parser = argparse.ArgumentParser(description=g.t('linux_description'), parents=[language])
    parser.add_argument('--shell', choices=('auto', 'bash', 'fish', 'zsh'), default='auto', help=g.t('linux_shell_help'))
    parser.add_argument('--check', action='store_true', help=g.t('linux_check_help'))
    args = parser.parse_args(argv)
    try:
        if sys.platform != 'linux':
            raise ValueError(g.t('linux_only'))
        shell = Path(os.environ.get('SHELL', '')).name if args.shell == 'auto' else args.shell
        if shell not in ('bash', 'fish', 'zsh'):
            raise ValueError(g.t('linux_shell'))
        prerequisites(shell)
        print(g.t('linux_testing'), flush=True)
        environment = dict(os.environ, LANG='C.UTF-8', LC_ALL='C.UTF-8',
                           PYTHONDONTWRITEBYTECODE='1')
        result = subprocess.run([sys.executable, '-B', '-m', 'unittest', 'discover',
                                 '-s', 'tests', '-q'], cwd=ROOT, env=environment)
        if result.returncode:
            raise ValueError(g.t('linux_tests_failed'))
        if args.check:
            print(g.t('linux_check_ok', shell=shell))
            return 0
        home = Path.home()
        config = Path(os.environ.get('XDG_CONFIG_HOME') or home / '.config')
        zdotdir = Path(os.environ.get('ZDOTDIR') or home)
        wrapper = install(ROOT, home, shell, config, zdotdir)
        print(g.t('linux_installed', shell=shell, p=g.display_git_path(wrapper)))
        print(g.t('linux_activate', command='source ' + (quote_fish(str(wrapper)) if shell == 'fish' else shlex.quote(str(wrapper)))))
        return 0
    except (OSError, ValueError, ImportError, subprocess.SubprocessError) as exc:
        print(g.t('linux_failed', e=g.terminal_text(exc)), file=sys.stderr)
        if isinstance(exc, DependencyError):
            print(f'CachyOS: sudo pacman -S --needed python git {shell}\n'
                  f'Linux Mint: sudo apt install python3 git {shell}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
