#!/usr/bin/env python3
"""Shell-Wrapper im Benutzerkonto einrichten."""

from __future__ import annotations

import argparse
import datetime
import os
import re
import shlex
import shutil
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import gitmaster_flash as g  # noqa: E402

MARKER = "# Generated by gitmaster_flash install-linux.sh"
START = "# >>> gitmaster_flash >>>"
END = "# <<< gitmaster_flash <<<"


class DependencyError(ValueError):
    pass


def quote_fish(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def wrapper_text(repo: Path, shell: str) -> str:
    script = str(repo / "gitmaster_flash.py")
    if shell == "fish":
        return (
            MARKER
            + "\n"
            + """function gmf
    set -l gmf_tmp /tmp
    if set -q TMPDIR; and test -n "$TMPDIR"
        set gmf_tmp "$TMPDIR"
    end
    set -l gmf_cdfile (mktemp "$gmf_tmp/gmf-cd.XXXXXXXX"); or return 1
    command python3 SCRIPT --cd-file "$gmf_cdfile" $argv
    set -l gmf_result $status
    set -l gmf_target ''
    if test -s "$gmf_cdfile"
        read --null --delimiter '' gmf_target < "$gmf_cdfile"
    end
    command rm -f -- "$gmf_cdfile"
    if test -n "$gmf_target"; and test -d "$gmf_target"
        cd -- "$gmf_target"; or return 1
    end
    return $gmf_result
end
""".replace("SCRIPT", quote_fish(script))
        )
    return (
        MARKER
        + "\n"
        + """gmf() {
    local gmf_cdfile gmf_target='' gmf_result=0
    gmf_cdfile=$(mktemp "${TMPDIR:-/tmp}/gmf-cd.XXXXXXXX") || return 1
    command python3 SCRIPT --cd-file "$gmf_cdfile" "$@" || gmf_result=$?
    if [ -s "$gmf_cdfile" ]; then
        IFS= read -r -d '' gmf_target < "$gmf_cdfile" || :
    fi
    command rm -f -- "$gmf_cdfile"
    if [ -n "$gmf_target" ] && [ -d "$gmf_target" ]; then
        cd -- "$gmf_target" || return 1
    fi
    return "$gmf_result"
}
""".replace("SCRIPT", shlex.quote(script))
    )


def checked_syntax(shell: str, content: bytes) -> None:
    options = {
        "bash": ["--noprofile", "--norc", "-n"],
        "zsh": ["-f", "-o", "NO_BG_NICE", "-n"],
        "fish": ["--no-config", "-n"],
    }
    environment = dict(os.environ)
    for key in ("BASH_ENV", "ENV"):
        environment.pop(key, None)
    result = subprocess.run(
        [shell, *options[shell]], input=content, capture_output=True, timeout=10, env=environment
    )
    if result.returncode or result.stderr:
        raise ValueError(g.t("linux_syntax", shell=shell))


def regular_contents(path: Path) -> bytes | None:
    try:
        mode = path.lstat().st_mode
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(mode):
        raise ValueError(g.t("linux_file_conflict", p=g.display_git_path(path)))
    return path.read_bytes()


def atomic_write(path: Path, data: bytes, *, expected: bytes | None, backup: bool = False) -> None:
    if regular_contents(path) != expected:
        raise ValueError(g.t("linux_file_conflict", p=g.display_git_path(path)))
    if expected == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(path.stat().st_mode) if expected is not None else 0o600
    if backup and expected is not None:
        timestamp = (
            datetime.datetime.now(datetime.timezone.utc)
            .isoformat(timespec="microseconds")
            .replace("+00:00", "Z")
        )
        saved = path.with_name(path.name + ".gmf-backup-" + timestamp)
        saved_fd = os.open(saved, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
        with os.fdopen(saved_fd, "wb") as stream:
            stream.write(expected)
        saved.chmod(mode)
    fd, temporary = tempfile.mkstemp(prefix=".gmf-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            os.fchmod(stream.fileno(), mode)
        if regular_contents(path) != expected:
            raise ValueError(g.t("linux_file_conflict", p=g.display_git_path(path)))
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def source_block(quoted_wrapper: str) -> bytes:
    return os.fsencode(f"{START}\nsource -- {quoted_wrapper}\n{END}\n")


def managed_block(original: bytes, *allowed: bytes) -> bytes | None:
    lines = original.splitlines(keepends=True)
    starts = [i for i, line in enumerate(lines) if line.rstrip(b"\r\n") == START.encode()]
    ends = [i for i, line in enumerate(lines) if line.rstrip(b"\r\n") == END.encode()]
    if not starts and not ends:
        return None
    if len(starts) == len(ends) == 1 and starts[0] < ends[0]:
        block = b"".join(lines[starts[0] : ends[0] + 1])
        if block in allowed:
            return block
    raise ValueError(g.t("linux_registration_conflict"))


def active_lines(content: bytes) -> bytes:
    return b"\n".join(line for line in content.splitlines() if not line.lstrip().startswith(b"#"))


STARTUP_COMMAND = (
    rb"(?:^|[;(){}&|])[ \t]*"
    rb"(?:(?:if|then|elif|else|while|until|do|!|builtin|command|noglob|nocorrect|time)[ \t]+)*"
)


def check_definitions(content: bytes) -> None:
    name = rb"(?:gmf|source|\.)"
    quoted_name = rb"(?:" + name + rb"|'" + name + rb"'|\"" + name + rb"\")"
    definitions = (
        rb"(?:function[ \t]+)?" + quoted_name + rb"[ \t]*\([ \t]*\)",
        rb"function[ \t]+(?:--[ \t]+)?" + quoted_name + rb"(?=[ \t;{(]|$)",
        rb"alias[ \t]+(?:[^;\n]*[ \t])?['\"]?" + name + rb"(?:['\"])?[= \t]",
        rb"(?:unfunction|unset[ \t]+-f)[ \t]+(?:--[ \t]+)?" + quoted_name + rb"(?=[ \t;]|$)",
        rb"disable[ \t]+(?:source|\.)\b",
    )
    if any(
        re.search(STARTUP_COMMAND + definition, content, re.MULTILINE) for definition in definitions
    ):
        raise ValueError(g.t("linux_registration_conflict"))


def check_errexit(content: bytes, shell: str) -> None:
    if re.search(
        STARTUP_COMMAND + rb"(?:"
        rb"set[ \t]+(?:-[A-Za-z]*e[A-Za-z]*|(?:-[A-Za-z]+[ \t]+)*-o[ \t]+errexit)"
        rb"|setopt[ \t]+(?:[^;\n]*[ \t])?(?:errexit|err_?exit))(?=[ \t;]|$)",
        content,
        re.MULTILINE | re.IGNORECASE,
    ):
        raise ValueError(g.t("install_unsafe_rc", shell=shell))


def check_bashrc(content: bytes, installed_block: bytes | None) -> None:
    active = active_lines(content.replace(installed_block, b"") if installed_block else content)
    # Ohne Zeilenumbruch kann ein Name über mehrere physische Zeilen verteilt sein.
    active = re.sub(rb"(?<!\\)((?:\\\\)*)\\\n", rb"\1", active)
    if b"<<" in active:
        raise ValueError(g.t("linux_complex_rc"))
    check_definitions(active)
    check_errexit(active, "bash")
    if re.search(rb"(?m)^[ \t]*[^#\n]*(?:source|\.)[ \t]+[^\n]*gmf\.(?:zsh|bash)", active):
        raise ValueError(g.t("linux_registration_conflict"))
    # Startdateien von Debian/Mint und Arch beenden gezielt nur nichtinteraktive Shells.
    active = re.sub(
        rb'(?m)^[ \t]*case[ \t]+(?:\$-|"\$-")[ \t]+in[ \t]*\n'
        rb"[ \t]*\*i\*\)[ \t]*;;[ \t]*\n"
        rb"[ \t]*\*\)[ \t]*return[ \t]*;;[ \t]*\n[ \t]*esac[ \t]*$",
        b"",
        active,
    )
    active = re.sub(
        rb'(?m)^[ \t]*\[\[[ \t]+(?:\$-|"\$-")[ \t]+!=[ \t]+\*i\*'
        rb"[ \t]+\]\][ \t]*&&[ \t]*return[ \t]*$",
        b"",
        active,
    )
    words = shlex.shlex(os.fsdecode(active), posix=True, punctuation_chars=True)
    words.whitespace_split = True
    if any(word in ("return", "exit", "exec") for word in words):
        raise ValueError(g.t("install_unsafe_rc", shell="bash"))


def run_zsh_checker(*args: str, content: bytes = b"") -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(
        ["zsh", "-f", str(ROOT / "tools/check-zshrc.zsh"), *args],
        input=content,
        capture_output=True,
        timeout=30,
    )


def check_zshrc(content: bytes, wrapper: Path, legacy: Path) -> Path | None:
    active = active_lines(content)
    check_definitions(active)
    check_errexit(active, "zsh")
    result = run_zsh_checker(str(wrapper), str(legacy), shlex.quote(str(legacy)), content=content)
    if result.returncode == 2:
        raise ValueError(g.t("install_different_path"))
    if result.returncode or result.stderr:
        raise ValueError(g.t("install_unsafe_rc", shell="zsh"))
    return Path(os.fsdecode(result.stdout.removesuffix(b"\n"))) if result.stdout else None


def appended_block(original: bytes, block: bytes) -> bytes:
    # Ein Backslash am Dateiende kann den ersten Umbruch verbrauchen.
    return original + (b"\n\n" if original else b"") + block


def check_fish_config(config: Path) -> None:
    for path in (config / "fish/config.fish", *(config / "fish/conf.d").glob("*.fish")):
        try:
            content = active_lines(path.read_bytes())
        except FileNotFoundError:
            continue
        check_definitions(content)
        if re.search(
            STARTUP_COMMAND + rb"(?:set[ \t]+[^;\n]*\bfish_function_path\b|exit\b)",
            content,
            re.MULTILINE,
        ):
            raise ValueError(g.t("install_unsafe_rc", shell="fish"))


def install_zsh(repo: Path, rc: Path, legacy: Path) -> tuple[Path, bool]:
    wrapper = repo / "gmf.zsh"
    checked_syntax("zsh", wrapper.read_bytes())
    quoted = run_zsh_checker("--quote", str(wrapper))
    if quoted.returncode or quoted.stderr:
        raise ValueError(g.t("install_unsafe_rc", shell="zsh"))
    block = source_block(os.fsdecode(quoted.stdout))
    legacy_block = source_block(shlex.quote(str(legacy)))
    original = regular_contents(rc)
    contents = original or b""
    managed = managed_block(contents, block, legacy_block)
    existing = check_zshrc(contents, wrapper, legacy)
    checked_syntax("zsh", contents)
    if existing == wrapper.resolve() and managed != legacy_block:
        return wrapper, True
    if existing == legacy.resolve() and managed == legacy_block:
        if regular_contents(legacy) != os.fsencode(wrapper_text(repo, "zsh")):
            raise ValueError(g.t("linux_file_conflict", p=g.display_git_path(legacy)))
        return legacy, True
    if existing is not None:
        raise ValueError(g.t("install_different_path"))
    if managed is not None:
        raise ValueError(g.t("install_unsafe_rc", shell="zsh"))
    updated = appended_block(contents, block)
    if check_zshrc(updated, wrapper, legacy) != wrapper.resolve():
        raise ValueError(g.t("install_unsafe_rc", shell="zsh"))
    checked_syntax("zsh", updated)
    atomic_write(rc, updated, backup=True, expected=original)
    return wrapper, False


def install(repo: Path, home: Path, shell: str, config: Path, zdotdir: Path) -> tuple[Path, bool]:
    if shell not in ("bash", "fish", "zsh"):
        raise ValueError(g.t("linux_shell"))
    if not all(p.is_absolute() for p in (repo, home, config, zdotdir)):
        raise ValueError(g.t("linux_absolute"))
    if shell == "zsh":
        return install_zsh(repo, zdotdir / ".zshrc", config / "gitmaster_flash/shell/gmf.zsh")
    wrapper = (
        config / "fish/functions/gmf.fish"
        if shell == "fish"
        else config / "gitmaster_flash/shell/gmf.bash"
    )
    content = os.fsencode(wrapper_text(repo, shell))
    previous = regular_contents(wrapper)
    if previous is not None and previous != content:
        raise ValueError(g.t("linux_file_conflict", p=g.display_git_path(wrapper)))
    checked_syntax(shell, content)
    if shell == "fish":
        check_fish_config(config)
        atomic_write(wrapper, content, expected=previous)
        return wrapper, previous == content

    rc = home / ".bashrc"
    original = regular_contents(rc)
    contents = original or b""
    block = source_block(shlex.quote(str(wrapper)))
    managed = managed_block(contents, block)
    check_bashrc(contents, managed)
    if managed is not None:
        checked_syntax("bash", contents.partition(managed)[0])
    checked_syntax("bash", contents)
    if managed is not None and previous is None:
        raise ValueError(g.t("linux_file_conflict", p=g.display_git_path(wrapper)))
    updated = contents if managed else appended_block(contents, block)
    checked_syntax("bash", updated)
    atomic_write(wrapper, content, expected=previous)
    atomic_write(rc, updated, backup=True, expected=original)
    return wrapper, managed is not None


def prerequisites(shell: str) -> None:
    if sys.version_info < (3, 9) or not shutil.which("git") or not shutil.which(shell):
        raise DependencyError(g.t("linux_dependencies", shell=shell))
    version = subprocess.run(["git", "--version"], capture_output=True, text=True, timeout=10)
    match = re.search(r"(\d+)\.(\d+)", version.stdout)
    if version.returncode or match is None or tuple(map(int, match.groups())) < (2, 36):
        raise DependencyError(g.t("linux_dependencies", shell=shell))


def activation_command(shell: str, wrapper: Path) -> str:
    path = str(wrapper)
    if g.terminal_text(path) == path:
        quoted = quote_fish(path) if shell == "fish" else shlex.quote(path)
    elif shell == "zsh":
        quoted = g.zsh_quote(path)
    elif shell == "bash":
        quoted = "$'" + "".join(f"\\{byte:03o}" for byte in os.fsencode(path)) + "'"
    else:
        result = subprocess.run(
            ["fish", "--no-config", "-c", 'string escape -- "$argv[1]"', "--", path],
            capture_output=True,
            check=True,
            timeout=10,
        )
        quoted = os.fsdecode(result.stdout.removesuffix(b"\n"))
    return "source " + quoted


def main(argv: list[str] | None = None) -> int:
    language = argparse.ArgumentParser(add_help=False)
    language.add_argument("--lang", choices=("en", "de"))
    known, _ = language.parse_known_args(argv)
    g.set_ui_lang(g.resolve_lang(g.DEFAULT_CONFIG, known.lang))
    parser = argparse.ArgumentParser(description=g.t("install_description"), parents=[language])
    parser.add_argument("--linux-only", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument(
        "--shell", choices=("auto", "bash", "fish", "zsh"), help=g.t("linux_shell_help")
    )
    parser.add_argument("--check", action="store_true", help=g.t("linux_check_help"))
    args = parser.parse_args(argv)
    shell = args.shell or ("zsh" if sys.platform == "darwin" else "auto")
    if shell == "auto":
        shell = Path(os.environ.get("SHELL", "")).name
    try:
        if args.linux_only and sys.platform != "linux":
            raise ValueError(g.t("linux_only"))
        if shell not in ("bash", "fish", "zsh"):
            raise ValueError(g.t("linux_shell"))
        prerequisites(shell)
        print(g.t("linux_testing"), flush=True)
        environment = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
        result = subprocess.run(
            [sys.executable, "-B", "-m", "unittest", "discover", "-s", "tests", "-q"],
            cwd=ROOT,
            env=environment,
        )
        if result.returncode:
            raise ValueError(g.t("linux_tests_failed"))
        if args.check:
            print(g.t("install_check_ok", shell=shell))
            return 0
        home = Path.home()
        config = Path(os.environ.get("XDG_CONFIG_HOME") or home / ".config")
        zdotdir = Path(os.environ.get("ZDOTDIR") or home)
        wrapper, existing = install(ROOT, home, shell, config, zdotdir)
        status = "install_existing" if existing else "install_registered"
        print(g.t(status, shell=shell, p=g.display_git_path(wrapper)))
        print(g.t("linux_activate", command=activation_command(shell, wrapper)))
        return 0
    except (OSError, ValueError, ImportError, subprocess.SubprocessError) as exc:
        print(g.t("linux_failed", e=g.terminal_text(exc)), file=sys.stderr)
        if isinstance(exc, DependencyError) and sys.platform == "linux":
            print(
                f"CachyOS: sudo pacman -S --needed python git {shell}\n"
                f"Linux Mint: sudo apt install python3 git {shell}",
                file=sys.stderr,
            )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
